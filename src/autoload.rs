type PackageMap<'a> = Vec<(&'a Package, Option<String>)>;

/// `AutoloadGenerator::buildPackageMap`: root first with path '', then installed packages.
pub fn build_package_map<'a>(
    vendor_dir: &str,
    root: &'a Package,
    packages: &[&'a Package],
) -> Result<PackageMap<'a>, String> {
    let mut map: PackageMap<'a> = vec![(root, Some(String::new()))];
    for package in packages {
        if package.alias_of.is_some() {
            continue;
        }
        validate_package(package)?;
        map.push((package, crate::installer::install_path(vendor_dir, package)));
    }
    Ok(map)
}

fn validate_package(package: &Package) -> Result<(), String> {
    if let Some(Value::Object(psr4)) = package.autoload.get("psr-4")
        && !psr4.is_empty()
    {
        if package.target_dir.is_some() {
            return Err(format!(
                "PSR-4 autoloading is incompatible with the target-dir property, remove the target-dir in package '{}'.",
                package.name
            ));
        }
        for namespace in psr4.keys() {
            if !namespace.is_empty() && !namespace.ends_with('\\') {
                return Err(format!(
                    "psr-4 namespaces must end with a namespace separator, '{namespace}' does not, use '{namespace}\\'."
                ));
            }
        }
    }
    Ok(())
}

#[derive(Debug, Default)]
pub struct Autoloads {
    pub psr0: Vec<(String, Vec<String>)>,
    pub psr4: Vec<(String, Vec<String>)>,
    pub classmap: Vec<String>,
    pub files: Vec<(String, String)>,
    pub exclude: Vec<String>,
}

/// `strnatcasecmp`
fn natcasecmp(a: &str, b: &str) -> std::cmp::Ordering {
    let a = a.to_lowercase();
    let b = b.to_lowercase();
    let (ab, bb) = (a.as_bytes(), b.as_bytes());
    let (mut i, mut j) = (0, 0);
    while i < ab.len() && j < bb.len() {
        if ab[i].is_ascii_digit() && bb[j].is_ascii_digit() {
            let si = i;
            while i < ab.len() && ab[i].is_ascii_digit() {
                i += 1;
            }
            let sj = j;
            while j < bb.len() && bb[j].is_ascii_digit() {
                j += 1;
            }
            let na = a[si..i].trim_start_matches('0');
            let nb = b[sj..j].trim_start_matches('0');
            let ord = na.len().cmp(&nb.len()).then_with(|| na.cmp(nb));
            if ord != std::cmp::Ordering::Equal {
                return ord;
            }
        } else {
            if ab[i] != bb[j] {
                return ab[i].cmp(&bb[j]);
            }
            i += 1;
            j += 1;
        }
    }
    (ab.len() - i).cmp(&(bb.len() - j))
}

/// `PackageSorter::sortPackages`
fn sort_packages<'a>(
    packages: &[(&'a Package, Option<String>)],
    root: &Package,
) -> Vec<(&'a Package, Option<String>)> {
    let mut usage: HashMap<String, Vec<String>> = HashMap::new();
    for (package, _) in packages {
        let mut links: Vec<&str> = package.requires.iter().map(|l| l.target.as_str()).collect();
        if std::ptr::eq(*package, root) {
            links.extend(package.dev_requires.iter().map(|l| l.target.as_str()));
        }
        for target in links {
            usage
                .entry(target.to_string())
                .or_default()
                .push(package.name.clone());
        }
    }
    fn importance(
        name: &str,
        usage: &HashMap<String, Vec<String>>,
        computing: &mut HashSet<String>,
        computed: &mut HashMap<String, i64>,
    ) -> i64 {
        if let Some(w) = computed.get(name) {
            return *w;
        }
        if computing.contains(name) {
            return 0;
        }
        computing.insert(name.to_string());
        let mut weight = 0;
        if let Some(users) = usage.get(name) {
            for user in users {
                weight -= 1 - importance(user, usage, computing, computed);
            }
        }
        computing.remove(name);
        computed.insert(name.to_string(), weight);
        weight
    }
    let mut computing = HashSet::new();
    let mut computed = HashMap::new();
    let mut weighted: Vec<(i64, usize)> = packages
        .iter()
        .enumerate()
        .map(|(i, (p, _))| {
            (
                importance(&p.name, &usage, &mut computing, &mut computed),
                i,
            )
        })
        .collect();
    weighted.sort_by(|a, b| {
        a.0.cmp(&b.0)
            .then_with(|| natcasecmp(&packages[a.1].0.name, &packages[b.1].0.name))
    });
    weighted
        .into_iter()
        .map(|(_, i)| (packages[i].0, packages[i].1.clone()))
        .collect()
}

/// `AutoloadGenerator::filterPackageMap`: the legacy dev filter when no dev package names are known.
fn filter_package_map<'a>(
    map: &[(&'a Package, Option<String>)],
    root: &Package,
) -> Vec<(&'a Package, Option<String>)> {
    let packages: HashMap<&str, &Package> =
        map.iter().map(|(p, _)| (p.name.as_str(), *p)).collect();
    let mut replaced_by: HashMap<String, String> = HashMap::new();
    for (p, _) in map {
        for r in &p.replaces {
            replaced_by.insert(r.target.clone(), p.name.clone());
        }
    }
    let mut include: HashSet<String> = HashSet::new();
    fn add(
        package: &Package,
        packages: &HashMap<&str, &Package>,
        include: &mut HashSet<String>,
        replaced_by: &HashMap<String, String>,
    ) {
        for link in &package.requires {
            let target = replaced_by
                .get(&link.target)
                .cloned()
                .unwrap_or_else(|| link.target.clone());
            if include.insert(target.clone())
                && let Some(p) = packages.get(target.as_str())
            {
                add(p, packages, include, replaced_by);
            }
        }
    }
    add(root, &packages, &mut include, &replaced_by);
    map.iter()
        .filter(|(p, _)| {
            std::iter::once(p.name.as_str())
                .chain(p.provides.iter().map(|l| l.target.as_str()))
                .chain(p.replaces.iter().map(|l| l.target.as_str()))
                .any(|n| include.contains(n))
        })
        .map(|(p, path)| (*p, path.clone()))
        .collect()
}

/// `AutoloadGenerator::parseAutoloads`
pub fn parse_autoloads(
    package_map: &PackageMap<'_>,
    root: &Package,
    filtered_dev: Option<&[String]>,
    dev_mode: bool,
    legacy_filter: bool,
) -> Autoloads {
    let root_entry = package_map
        .first()
        .filter(|(p, _)| std::ptr::eq(*p, root))
        .cloned();
    let mut rest: Vec<(&Package, Option<String>)> = package_map
        .iter()
        .skip(usize::from(root_entry.is_some()))
        .map(|(p, path)| (*p, path.clone()))
        .collect();
    if legacy_filter {
        rest = filter_package_map(&rest, root);
    } else if let Some(dev) = filtered_dev {
        rest.retain(|(p, _)| !dev.contains(&p.name));
    }
    let mut sorted = sort_packages(&rest, root);
    if let Some(r) = root_entry {
        sorted.push(r);
    }
    let reversed: Vec<(&Package, Option<String>)> = sorted.iter().rev().cloned().collect();

    let mut autoloads = Autoloads {
        psr0: parse_namespaced(&reversed, "psr-0", root, dev_mode),
        psr4: parse_namespaced(&reversed, "psr-4", root, dev_mode),
        classmap: parse_list(&reversed, "classmap", root, dev_mode),
        files: parse_files(&sorted, root, dev_mode),
        exclude: parse_exclude(&sorted, root, dev_mode),
    };
    // krsort
    autoloads.psr0.sort_by(|a, b| b.0.cmp(&a.0));
    autoloads.psr4.sort_by(|a, b| b.0.cmp(&a.0));
    autoloads
}

fn package_autoload(
    package: &Package,
    root: &Package,
    dev_mode: bool,
    kind: &str,
) -> Vec<(String, Vec<String>)> {
    let mut entries: Vec<(String, Vec<String>)> = Vec::new();
    let mut collect = |section: &serde_json::Map<String, Value>| {
        if let Some(value) = section.get(kind) {
            let items: Vec<(String, Value)> = match value {
                Value::Object(o) => o.iter().map(|(k, v)| (k.clone(), v.clone())).collect(),
                Value::Array(a) => a
                    .iter()
                    .enumerate()
                    .map(|(i, v)| (i.to_string(), v.clone()))
                    .collect(),
                _ => return,
            };
            for (ns, paths) in items {
                let paths: Vec<String> = match paths {
                    Value::Array(a) => a
                        .iter()
                        .filter_map(|v| v.as_str().map(str::to_string))
                        .collect(),
                    Value::String(s) => vec![s],
                    _ => vec![],
                };
                match entries.iter_mut().find(|(n, _)| *n == ns) {
                    Some((_, existing)) if value.is_object() => existing.extend(paths),
                    _ => entries.push((ns, paths)),
                }
            }
        }
    };
    collect(&package.autoload);
    if dev_mode && std::ptr::eq(package, root) {
        // array_merge_recursive: list entries append, string keys merge
        collect(&package.dev_autoload);
    }
    entries
}

fn strip_target_dir(package: &Package, root: &Package, install_path: &str) -> String {
    match &package.target_dir {
        Some(t) if !t.is_empty() && !std::ptr::eq(package, root) => {
            install_path[..install_path.len().saturating_sub(t.len() + 1)].to_string()
        }
        _ => install_path.to_string(),
    }
}

fn adjust_path_for_target_dir(
    package: &Package,
    root: &Package,
    install_path: &str,
    path: &str,
) -> String {
    if let Some(target) = package.target_dir.as_deref().filter(|t| !t.is_empty())
        && !Path::new(&format!("{install_path}/{path}")).exists()
    {
        if std::ptr::eq(package, root) {
            let quoted = regex::escape(&target.replace(['/', '\\'], "<dirsep>"))
                .replace("<dirsep>", "[\\\\/]");
            let re = Regex::new(&format!("^{quoted}")).unwrap();
            return re
                .replace(path.trim_start_matches(['\\', '/']), "")
                .trim_start_matches(['\\', '/'])
                .to_string();
        }
        return format!("{target}/{path}");
    }
    path.to_string()
}

fn parse_namespaced(
    map: &[(&Package, Option<String>)],
    kind: &str,
    root: &Package,
    dev_mode: bool,
) -> Vec<(String, Vec<String>)> {
    let mut out: Vec<(String, Vec<String>)> = Vec::new();
    for (package, install_path) in map {
        let Some(install_path) = install_path else {
            continue;
        };
        let install_path = strip_target_dir(package, root, install_path);
        for (namespace, paths) in package_autoload(package, root, dev_mode, kind) {
            let namespace = namespace.trim_start_matches('\\').to_string();
            for path in paths {
                let relative = if install_path.is_empty() {
                    if path.is_empty() { ".".into() } else { path }
                } else {
                    format!("{install_path}/{path}")
                };
                match out.iter_mut().find(|(n, _)| *n == namespace) {
                    Some((_, list)) => list.push(relative),
                    None => out.push((namespace.clone(), vec![relative])),
                }
            }
        }
    }
    out
}

fn parse_list(
    map: &[(&Package, Option<String>)],
    kind: &str,
    root: &Package,
    dev_mode: bool,
) -> Vec<String> {
    let mut out = Vec::new();
    for (package, install_path) in map {
        let Some(install_path) = install_path else {
            continue;
        };
        let install_path = strip_target_dir(package, root, install_path);
        for (_, paths) in package_autoload(package, root, dev_mode, kind) {
            for path in paths {
                let path = adjust_path_for_target_dir(package, root, &install_path, &path);
                out.push(if install_path.is_empty() {
                    if path.is_empty() { ".".into() } else { path }
                } else {
                    format!("{install_path}/{path}")
                });
            }
        }
    }
    out
}

fn parse_files(
    map: &[(&Package, Option<String>)],
    root: &Package,
    dev_mode: bool,
) -> Vec<(String, String)> {
    let mut out: Vec<(String, String)> = Vec::new();
    for (package, install_path) in map {
        let Some(install_path) = install_path else {
            continue;
        };
        let install_path = strip_target_dir(package, root, install_path);
        for (_, paths) in package_autoload(package, root, dev_mode, "files") {
            for path in paths {
                let path = adjust_path_for_target_dir(package, root, &install_path, &path);
                let relative = if install_path.is_empty() {
                    if path.is_empty() {
                        ".".into()
                    } else {
                        path.clone()
                    }
                } else {
                    format!("{install_path}/{path}")
                };
                let id = format!("{:x}", md5::compute(format!("{}:{path}", package.name)));
                match out.iter_mut().find(|(i, _)| *i == id) {
                    Some((_, p)) => *p = relative,
                    None => out.push((id, relative)),
                }
            }
        }
    }
    out
}

fn parse_exclude(
    map: &[(&Package, Option<String>)],
    root: &Package,
    dev_mode: bool,
) -> Vec<String> {
    let mut out = Vec::new();
    for (package, install_path) in map {
        let Some(install_path) = install_path else {
            continue;
        };
        let install_path = strip_target_dir(package, root, install_path);
        for (_, paths) in package_autoload(package, root, dev_mode, "exclude-from-classmap") {
            for path in paths {
                let path = adjust_path_for_target_dir(package, root, &install_path, &path);
                let mut pattern = regex::escape(path.replace('\\', "/").trim_matches('/'));
                pattern = SLASHES.replace_all(&pattern, "/").into_owned();
                pattern = pattern.replace("\\*\\*", ".+?").replace("\\*", "[^/]+?");
                let mut updir = String::new();
                if let Some(m) = UPDIR.captures(&pattern) {
                    updir = m[1].replace("\\.", ".");
                    pattern = pattern[m[0].len()..].to_string();
                }
                let base = if install_path.is_empty() {
                    crate::fs::cwd().replace('\\', "/")
                } else {
                    install_path.clone()
                };
                let Ok(resolved) = std::fs::canonicalize(format!("{base}/{updir}")) else {
                    continue;
                };
                out.push(format!(
                    "{}/{pattern}($|/)",
                    regex::escape(&resolved.to_string_lossy().replace('\\', "/"))
                ));
            }
        }
    }
    out
}

fn exclusion_regex_with_vendor(dir: &str, excluded: &[String], vendor_path: &str) -> Option<Regex> {
    let mut excluded = excluded.to_vec();
    let resolved = normalize_path(&if is_absolute_path(dir) {
        dir.to_string()
    } else {
        format!("{}/{dir}", realpath(Path::new(&crate::fs::cwd())))
    });
    if vendor_path.starts_with(&format!("{resolved}/")) {
        excluded.push(regex::escape(&format!("{vendor_path}/")));
    }
    exclusion_regex(dir, &excluded)
}

fn exclusion_regex(dir: &str, excluded: &[String]) -> Option<Regex> {
    if excluded.is_empty() {
        return None;
    }
    let mut excluded = excluded.to_vec();
    if Path::new(dir).exists() {
        let dir_match = regex::escape(&realpath(Path::new(dir)).replace('\\', "/"));
        let abs = if is_absolute_path(dir) {
            dir.to_string()
        } else {
            format!("{}/{dir}", realpath(Path::new(&crate::fs::cwd())))
        };
        let dir_match_normalized = regex::escape(&normalize_path(&abs).replace('\\', "/"));
        let is_symlink = dir_match != dir_match_normalized;
        let prefix_re =
            Regex::new(r"^((?:[^.+*?\[^\]$(){}=!<>|:\\#-]+|\\[.+*?\[^\]$(){}=!<>|:#-])*)").unwrap();
        excluded.retain(|pattern| {
            let prefix = prefix_re.find(pattern).map_or("", |m| m.as_str());
            let related = prefix.starts_with(&dir_match) || dir_match.starts_with(prefix);
            let related_norm = is_symlink
                && (prefix.starts_with(&dir_match_normalized)
                    || dir_match_normalized.starts_with(prefix));
            related || related_norm
        });
    }
    if excluded.is_empty() {
        return None;
    }
    Regex::new(&format!("({})", excluded.join("|"))).ok()
}

/// `AutoloadGenerator::getPathCode`
fn path_code(base_path: &str, vendor_path: &str, path: &str) -> String {
    let mut path = if is_absolute_path(path) {
        path.to_string()
    } else {
        format!("{base_path}/{path}")
    };
    path = normalize_path(&path);
    let mut base_dir = String::new();
    if format!("{path}/").starts_with(&format!("{vendor_path}/")) {
        path = path[vendor_path.len()..].to_string();
        base_dir = "$vendorDir . ".into();
    } else {
        path = normalize_path(&find_shortest_path(base_path, &path, true, false));
        if !is_absolute_path(&path) {
            base_dir = "$baseDir . ".into();
            path = format!("/{path}");
        }
    }
    if Regex::new(r"\.phar([\\/]|$)").unwrap().is_match(&path) {
        base_dir = format!("'phar://' . {base_dir}");
    }
    format!("{base_dir}{}", var_export_str(&path))
}

fn include_paths_file(
    map: &PackageMap<'_>,
    base_path: &str,
    vendor_path: &str,
    vendor_path_code: &str,
    app_base_dir_code: &str,
) -> Option<String> {
    let mut include_paths = Vec::new();
    for (package, install_path) in map {
        let Some(install_path) = install_path else {
            continue;
        };
        let install_path = match package.target_dir.as_deref().filter(|t| !t.is_empty()) {
            Some(t) => install_path[..install_path.len().saturating_sub(t.len() + 1)].to_string(),
            None => install_path.clone(),
        };
        for p in &package.include_paths {
            let p = p.trim_matches('/');
            include_paths.push(if install_path.is_empty() {
                p.to_string()
            } else {
                format!("{install_path}/{p}")
            });
        }
    }
    if include_paths.is_empty() {
        return None;
    }
    let mut code = String::new();
    for p in include_paths {
        code.push_str(&format!("    {},\n", path_code(base_path, vendor_path, &p)));
    }
    Some(format!(
        "<?php\n\n// include_paths.php @generated by Composer\n\n$vendorDir = {vendor_path_code};\n$baseDir = {app_base_dir_code};\n\nreturn array(\n{code});\n"
    ))
}

fn include_files_file(
    io: &mut Io,
    files: &[(String, String)],
    base_path: &str,
    vendor_path: &str,
    vendor_path_code: &str,
    app_base_dir_code: &str,
) -> Option<String> {
    let coded: Vec<(String, String)> = files
        .iter()
        .map(|(id, f)| (id.clone(), path_code(base_path, vendor_path, f)))
        .collect();
    let mut seen: HashSet<&str> = HashSet::new();
    let mut duplicates: Vec<&str> = Vec::new();
    for (_, code) in &coded {
        if !seen.insert(code) && !duplicates.contains(&code.as_str()) {
            duplicates.push(code);
        }
    }
    if !duplicates.is_empty() {
        io.error("The following \"files\" autoload rules are included multiple times, this may cause issues and should be resolved:");
        for d in duplicates {
            io.error(&format!(" - {d}"));
        }
    }
    if coded.is_empty() {
        return None;
    }
    let mut code = String::new();
    for (id, f) in &coded {
        code.push_str(&format!("    {} => {f},\n", var_export_str(id)));
    }
    Some(format!(
        "<?php\n\n// autoload_files.php @generated by Composer\n\n$vendorDir = {vendor_path_code};\n$baseDir = {app_base_dir_code};\n\nreturn array(\n{code});\n"
    ))
}

