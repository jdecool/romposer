#[derive(Clone, Debug, Default)]
pub struct DumpOptions {
    /// `--optimize`: scan PSR-0/4 directories into the classmap
    pub optimize: bool,
    pub authoritative: bool,
    pub apcu: bool,
    pub apcu_prefix: Option<String>,
    /// `None` infers from installed.json's `dev` flag
    pub dev_mode: Option<bool>,
    pub dry_run: bool,
    /// `setRunScripts`: fire `pre/post-autoload-dump`
    pub run_scripts: bool,
    pub strict_ambiguous: bool,
    pub ignore_all_platform_reqs: bool,
    pub ignored_platform_reqs: Vec<String>,
}

/// `AutoloadGenerator::dump` with `$targetDir = 'composer'`.
#[allow(clippy::too_many_arguments)]
pub fn dump(
    io: &mut Io,
    config: &Config,
    local_repo: &InstalledRepository,
    root: &RootPackage,
    lock: Option<&Lock>,
    options: &DumpOptions,
) -> Result<ClassMap, String> {
    let scan_psr = options.optimize || options.authoritative;
    let dev_mode = options
        .dev_mode
        .unwrap_or_else(|| local_repo.dev_mode.unwrap_or(false));
    if options.run_scripts {
        // set COMPOSER_DEV_MODE in case not set yet so it is available in the dump-autoload event listeners
        if crate::scripts::get_env("COMPOSER_DEV_MODE").is_none() {
            crate::scripts::put_env("COMPOSER_DEV_MODE", Some(if dev_mode { "1" } else { "0" }))?;
        }
        crate::scripts::fire(io, config, root, "pre-autoload-dump")?;
    }

    let vendor_dir = config.vendor_dir();
    ensure_dir(Path::new(&vendor_dir))?;
    let base_path = normalize_path(&realpath(Path::new(&crate::fs::cwd())));
    let vendor_path = normalize_path(&realpath(Path::new(&vendor_dir)));
    let use_global_include_path = config.bool("use-include-path");
    let prepend_autoloader = if config.config.get("prepend-autoloader") == Some(&Value::Bool(false))
    {
        "false"
    } else {
        "true"
    };
    let target_dir = format!("{vendor_path}/composer");
    ensure_dir(Path::new(&target_dir))?;
    let target_real = realpath(Path::new(&target_dir));

    let vendor_path_code = find_shortest_path_code(&target_real, &vendor_path, true, false, false);
    let vendor_path_to_target_dir_code =
        find_shortest_path_code(&vendor_path, &target_real, true, false, false);
    let app_base_dir_code = find_shortest_path_code(&vendor_path, &base_path, true, false, false)
        .replace("__DIR__", "$vendorDir");

    let header = |name: &str| {
        format!(
            "<?php\n\n// {name} @generated by Composer\n\n$vendorDir = {vendor_path_code};\n$baseDir = {app_base_dir_code};\n\nreturn array(\n"
        )
    };

    let dev_package_names = local_repo.dev_package_names.clone();
    let root_pkg = &root.package;
    let package_map = build_package_map(&vendor_dir, root_pkg, &local_repo.canonical_packages())?;
    let filtered_dev: Option<Vec<String>> = if dev_mode {
        None
    } else if !dev_package_names.is_empty() {
        Some(dev_package_names.clone())
    } else {
        Some(vec![]) // legacy filtering
    };
    let autoloads = parse_autoloads(
        &package_map,
        root_pkg,
        filtered_dev.as_deref(),
        dev_mode,
        !dev_mode && dev_package_names.is_empty(),
    );

    let mut namespaces_file = header("autoload_namespaces.php");
    for (namespace, paths) in &autoloads.psr0 {
        let exported: Vec<String> = paths
            .iter()
            .map(|p| path_code(&base_path, &vendor_path, p))
            .collect();
        namespaces_file.push_str(&format!(
            "    {} => array({}),\n",
            var_export_str(namespace),
            exported.join(", ")
        ));
    }
    namespaces_file.push_str(");\n");

    let mut psr4_file = header("autoload_psr4.php");
    for (namespace, paths) in &autoloads.psr4 {
        let exported: Vec<String> = paths
            .iter()
            .map(|p| path_code(&base_path, &vendor_path, p))
            .collect();
        psr4_file.push_str(&format!(
            "    {} => array({}),\n",
            var_export_str(namespace),
            exported.join(", ")
        ));
    }
    psr4_file.push_str(");\n");

    // custom psr-0 autoloading if the root package has a target dir
    let mut target_dir_loader: Option<String> = None;
    if let Some(root_target) = root_pkg.target_dir.as_deref().filter(|t| !t.is_empty())
        && let Some(Value::Object(psr0)) = root_pkg.autoload.get("psr-0")
        && !psr0.is_empty()
    {
        let levels = normalize_path(root_target).matches('/').count() + 1;
        let prefixes: Vec<String> = psr0.keys().map(|k| var_export_str(k)).collect();
        let base_dir_from_target =
            find_shortest_path_code(&target_dir, &base_path, true, false, false);
        target_dir_loader = Some(format!(
            "\n    public static function autoload($class)\n    {{\n        $dir = {base_dir_from_target} . '/';\n        $prefixes = array({});\n        foreach ($prefixes as $prefix) {{\n            if (0 !== strpos($class, $prefix)) {{\n                continue;\n            }}\n            $path = $dir . implode('/', array_slice(explode('\\\\', $class), {levels})).'.php';\n            if (!$path = stream_resolve_include_path($path)) {{\n                return false;\n            }}\n            require $path;\n\n            return true;\n        }}\n    }}\n",
            prefixes.join(", ")
        ));
    }

    let mut generator = ClassMapGenerator::new(&["php", "inc", "hh"]);
    generator.avoid_duplicate_scans();
    for dir in &autoloads.classmap {
        let excluded = exclusion_regex_with_vendor(dir, &autoloads.exclude, &vendor_path);
        generator.scan_paths(dir, excluded.as_ref(), "classmap", None)?;
    }
    if scan_psr {
        // namespaces sorted descending (krsort), psr-4 before psr-0 within a namespace
        let mut to_scan: BTreeMap<String, Vec<(&Vec<String>, &str)>> = BTreeMap::new();
        for (ns, paths) in &autoloads.psr4 {
            to_scan
                .entry(ns.clone())
                .or_default()
                .push((paths, "psr-4"));
        }
        for (ns, paths) in &autoloads.psr0 {
            to_scan
                .entry(ns.clone())
                .or_default()
                .push((paths, "psr-0"));
        }
        for (namespace, groups) in to_scan.iter().rev() {
            for (paths, kind) in groups {
                for dir in paths.iter() {
                    let dir = normalize_path(&if is_absolute_path(dir) {
                        dir.clone()
                    } else {
                        format!("{base_path}/{dir}")
                    });
                    if !Path::new(&dir).is_dir() {
                        continue;
                    }
                    let excluded =
                        exclusion_regex_with_vendor(&dir, &autoloads.exclude, &vendor_path);
                    generator.scan_paths(&dir, excluded.as_ref(), kind, Some(namespace))?;
                }
            }
        }
    }
    let mut class_map = generator.class_map;
    class_map.add_class(
        "Composer\\InstalledVersions",
        &format!("{vendor_path}/composer/InstalledVersions.php"),
    );

    let (ambiguous_classes, ambiguous_folders) = if options.strict_ambiguous {
        (
            class_map.ambiguous_classes(false),
            class_map.ambiguous_folders(false),
        )
    } else {
        (
            class_map.ambiguous_classes(true),
            class_map.ambiguous_folders(true),
        )
    };
    for (class, paths) in &ambiguous_classes {
        let first = class_map.class_path(class).unwrap_or("");
        if paths.len() > 1 {
            io.error(&format!(
                "Warning: Ambiguous class resolution, \"{class}\" was found {}x: in \"{first}\" and \"{}\", the first will be used.",
                paths.len() + 1,
                paths.join("\", \"")
            ));
        } else {
            io.error(&format!(
                "Warning: Ambiguous class resolution, \"{class}\" was found in both \"{first}\" and \"{}\", the first will be used.",
                paths.join("\", \"")
            ));
        }
    }
    for paths in &ambiguous_folders {
        io.error(&format!(
            "Warning: Ambiguous path casing, \"{}\" only differ in casing and merge into one on case-insensitive filesystems (e.g. Windows and macOS), which breaks autoloading there.",
            paths.join("\", \"")
        ));
    }
    if !ambiguous_classes.is_empty() || !ambiguous_folders.is_empty() {
        io.error("To resolve ambiguity in classes not under your control you can ignore them by path using exclude-from-classmap");
    }
    class_map.clear_psr_violations_by_path(&vendor_path);
    for msg in class_map.psr_violations() {
        io.error(&msg);
    }

    let mut classmap_file = header("autoload_classmap.php");
    for (class, path) in &class_map.map {
        classmap_file.push_str(&format!(
            "    {} => {},\n",
            var_export_str(class),
            path_code(&base_path, &vendor_path, path)
        ));
    }
    classmap_file.push_str(");\n");

    let mut suffix = config
        .get("autoloader-suffix")
        .and_then(Value::as_str)
        .filter(|s| !s.is_empty())
        .map(str::to_string);
    if suffix.is_none()
        && let Ok(content) = std::fs::read_to_string(format!("{vendor_path}/autoload.php"))
        && let Some(m) = Regex::new(r"ComposerAutoloaderInit([^:\s]+)::")
            .unwrap()
            .captures(&content)
    {
        suffix = Some(m[1].to_string());
    }
    let suffix = suffix.unwrap_or_else(|| {
        let hash = lock
            .filter(|l| l.is_locked())
            .and_then(|l| l.data.get("content-hash"))
            .and_then(Value::as_str);
        match hash {
            Some(h) if Regex::new(r"^[a-f0-9]+$").unwrap().is_match(h) => h.to_string(),
            _ => crate::fs::random_hex(16),
        }
    });

    if options.dry_run {
        return Ok(class_map);
    }

    write_if_modified(
        &format!("{target_dir}/autoload_namespaces.php"),
        &namespaces_file,
    )?;
    write_if_modified(&format!("{target_dir}/autoload_psr4.php"), &psr4_file)?;
    write_if_modified(
        &format!("{target_dir}/autoload_classmap.php"),
        &classmap_file,
    )?;

    let include_paths_file = include_paths_file(
        &package_map,
        &base_path,
        &vendor_path,
        &vendor_path_code,
        &app_base_dir_code,
    );
    let include_paths_path = format!("{target_dir}/include_paths.php");
    match &include_paths_file {
        Some(content) => write_if_modified(&include_paths_path, content)?,
        None => {
            let _ = std::fs::remove_file(&include_paths_path);
        }
    }
    let include_files_file = include_files_file(
        io,
        &autoloads.files,
        &base_path,
        &vendor_path,
        &vendor_path_code,
        &app_base_dir_code,
    );
    let include_files_path = format!("{target_dir}/autoload_files.php");
    match &include_files_file {
        Some(content) => write_if_modified(&include_files_path, content)?,
        None => {
            let _ = std::fs::remove_file(&include_files_path);
        }
    }

    let static_file = static_file(
        &suffix,
        &target_real,
        &vendor_path,
        &base_path,
        &autoloads,
        &class_map,
    );
    write_if_modified(&format!("{target_dir}/autoload_static.php"), &static_file)?;

    let platform_check_setting = config
        .config
        .get("platform-check")
        .cloned()
        .unwrap_or(Value::String("php-only".into()));
    let mut check_platform =
        platform_check_setting != Value::Bool(false) && !options.ignore_all_platform_reqs;
    let mut platform_check_content = None;
    if check_platform {
        platform_check_content = platform_check(
            &package_map,
            platform_check_setting == Value::Bool(true),
            &dev_package_names,
            &options.ignored_platform_reqs,
        );
        if platform_check_content.is_none() {
            check_platform = false;
        }
    }
    let platform_check_path = format!("{target_dir}/platform_check.php");
    if check_platform {
        write_if_modified(
            &platform_check_path,
            platform_check_content.as_deref().unwrap(),
        )?;
    } else {
        let _ = std::fs::remove_file(&platform_check_path);
    }

    write_if_modified(
        &format!("{vendor_path}/autoload.php"),
        &autoload_file(&vendor_path_to_target_dir_code, &suffix),
    )?;
    write_if_modified(
        &format!("{target_dir}/autoload_real.php"),
        &autoload_real_file(
            include_paths_file.is_some(),
            target_dir_loader.as_deref(),
            include_files_file.is_some(),
            &suffix,
            use_global_include_path,
            prepend_autoloader,
            check_platform,
            options,
        ),
    )?;
    write_if_modified(&format!("{target_dir}/ClassLoader.php"), CLASS_LOADER)?;
    write_if_modified(&format!("{target_dir}/LICENSE"), LICENSE)?;
    if options.run_scripts {
        crate::scripts::fire(io, config, root, "post-autoload-dump")?;
    }

    Ok(class_map)
}

/// `FilesystemRepository::write`'s installed.php and InstalledVersions.php part.
pub fn write_installed_versions(
    repo_dir: &str,
    local_repo: &InstalledRepository,
    root: &RootPackage,
    dev_mode: bool,
    install_path: impl Fn(&Package) -> Option<String>,
) -> Result<(), String> {
    let repo_dir = normalize_path(&realpath(Path::new(repo_dir)));
    let versions = installed_versions(&repo_dir, local_repo, root, dev_mode, install_path);
    let code = format!("<?php return {};\n", dump_php(&versions, 0));
    write_if_modified(&format!("{repo_dir}/installed.php"), &code)?;
    write_if_modified(
        &format!("{repo_dir}/InstalledVersions.php"),
        INSTALLED_VERSIONS,
    )?;
    Ok(())
}

fn write_if_modified(path: &str, content: &str) -> Result<(), String> {
    if std::fs::read_to_string(path).ok().as_deref() != Some(content) {
        std::fs::write(path, content).map_err(|e| format!("Could not write {path}: {e}"))?;
    }
    Ok(())
}

