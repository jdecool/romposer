fn installed_versions(
    repo_dir: &str,
    local_repo: &InstalledRepository,
    root: &RootPackage,
    dev_mode: bool,
    install_path: impl Fn(&Package) -> Option<String>,
) -> Php {
    let dev: HashSet<&str> = local_repo
        .dev_package_names
        .iter()
        .map(String::as_str)
        .collect();
    let cwd = crate::fs::cwd();
    let root_pkg = &root.package;
    let mut all: Vec<&Package> = local_repo.packages.iter().collect();
    all.push(root_pkg);
    let mut real_root = root_pkg;
    while let Some(r) = &real_root.alias_of {
        all.push(r);
        real_root = r;
    }

    let reference = |p: &Package| -> Php {
        let r = match p.installation_source.as_deref() {
            Some("source") => p.source.as_ref().and_then(|s| s.reference.clone()),
            Some(_) => p.dist.as_ref().and_then(|d| d.reference.clone()),
            None => None,
        }
        .or_else(|| {
            p.source
                .as_ref()
                .and_then(|s| s.reference.clone())
                .filter(|s| !s.is_empty())
        })
        .or_else(|| {
            p.dist
                .as_ref()
                .and_then(|d| d.reference.clone())
                .filter(|s| !s.is_empty())
        });
        r.map_or(Php::Null, Php::Str)
    };
    let rel_path = |p: &Package, is_root: bool| -> Php {
        if is_root {
            let to = normalize_path(&realpath(Path::new(&cwd)));
            return Php::Str(find_shortest_path(repo_dir, &to, true, false));
        }
        match install_path(p) {
            Some(abs) => {
                let normalized = normalize_path(&if is_absolute_path(&abs) {
                    abs
                } else {
                    format!("{cwd}/{abs}")
                });
                Php::Str(find_shortest_path(repo_dir, &normalized, true, false))
            }
            None => Php::Null,
        }
    };

    let root_entry = Php::Arr(vec![
        (PhpKey::Str("name".into()), Php::Str(root_pkg.name.clone())),
        (
            PhpKey::Str("pretty_version".into()),
            Php::Str(root_pkg.pretty_version.clone()),
        ),
        (
            PhpKey::Str("version".into()),
            Php::Str(root_pkg.version.clone()),
        ),
        (PhpKey::Str("reference".into()), reference(root_pkg)),
        (PhpKey::Str("type".into()), Php::Str(root_pkg.kind.clone())),
        (PhpKey::Str("install_path".into()), rel_path(root_pkg, true)),
        (PhpKey::Str("aliases".into()), Php::Arr(vec![])),
        (PhpKey::Str("dev".into()), Php::Bool(dev_mode)),
    ]);

    // versions: name => ordered map of fields
    let mut versions: BTreeMap<String, Vec<(String, Php)>> = BTreeMap::new();
    for p in &all {
        if p.alias_of.is_some() {
            continue;
        }
        let is_root = std::ptr::eq(*p, real_root) || std::ptr::eq(*p, root_pkg);
        versions.insert(
            p.name.clone(),
            vec![
                ("pretty_version".into(), Php::Str(p.pretty_version.clone())),
                ("version".into(), Php::Str(p.version.clone())),
                ("reference".into(), reference(p)),
                ("type".into(), Php::Str(p.kind.clone())),
                ("install_path".into(), rel_path(p, is_root)),
                ("aliases".into(), Php::Arr(vec![])),
                (
                    "dev_requirement".into(),
                    Php::Bool(dev.contains(p.name.as_str())),
                ),
            ],
        );
    }
    let set = |entry: &mut Vec<(String, Php)>, key: &str, value: Php| match entry
        .iter_mut()
        .find(|(k, _)| k == key)
    {
        Some((_, v)) => *v = value,
        None => entry.push((key.to_string(), value)),
    };
    for p in &all {
        let is_dev = dev.contains(p.name.as_str());
        for (links, key) in [(&p.replaces, "replaced"), (&p.provides, "provided")] {
            for link in links {
                if is_platform_package(&link.target) {
                    continue;
                }
                let entry = versions.entry(link.target.clone()).or_default();
                match entry.iter().position(|(k, _)| k == "dev_requirement") {
                    None => entry.push(("dev_requirement".into(), Php::Bool(is_dev))),
                    Some(i) => {
                        if !is_dev {
                            entry[i].1 = Php::Bool(false);
                        }
                    }
                }
                let constraint = if link.pretty_constraint == "self.version" {
                    p.pretty_version.clone()
                } else {
                    link.pretty_constraint.clone()
                };
                let list = match entry.iter_mut().find(|(k, _)| k == key) {
                    Some((_, Php::Arr(list))) => list,
                    _ => {
                        entry.push((key.to_string(), Php::Arr(vec![])));
                        match &mut entry.last_mut().unwrap().1 {
                            Php::Arr(list) => list,
                            _ => unreachable!(),
                        }
                    }
                };
                if !list
                    .iter()
                    .any(|(_, v)| matches!(v, Php::Str(s) if *s == constraint))
                {
                    list.push((PhpKey::Int(list.len() as i64), Php::Str(constraint)));
                }
            }
        }
    }
    let mut root_aliases: Vec<String> = Vec::new();
    for p in &all {
        if p.alias_of.is_none() {
            continue;
        }
        let entry = versions.entry(p.name.clone()).or_default();
        let list = match entry.iter_mut().find(|(k, _)| k == "aliases") {
            Some((_, Php::Arr(list))) => list,
            _ => {
                entry.push(("aliases".into(), Php::Arr(vec![])));
                match &mut entry.last_mut().unwrap().1 {
                    Php::Arr(list) => list,
                    _ => unreachable!(),
                }
            }
        };
        list.push((
            PhpKey::Int(list.len() as i64),
            Php::Str(p.pretty_version.clone()),
        ));
        if std::ptr::eq(*p, root_pkg) {
            root_aliases.push(p.pretty_version.clone());
        }
    }
    let _ = set;
    // sort aliases/replaced/provided naturally
    for entry in versions.values_mut() {
        for (k, v) in entry.iter_mut() {
            if matches!(k.as_str(), "aliases" | "replaced" | "provided")
                && let Php::Arr(list) = v
            {
                let mut strings: Vec<String> = list
                    .iter()
                    .filter_map(|(_, v)| {
                        if let Php::Str(s) = v {
                            Some(s.clone())
                        } else {
                            None
                        }
                    })
                    .collect();
                strings.sort_by(|a, b| natcmp(a, b));
                *list = strings
                    .into_iter()
                    .enumerate()
                    .map(|(i, s)| (PhpKey::Int(i as i64), Php::Str(s)))
                    .collect();
            }
        }
    }
    let mut root_entry = root_entry;
    if let Php::Arr(fields) = &mut root_entry
        && let Some((_, Php::Arr(list))) = fields
            .iter_mut()
            .find(|(k, _)| matches!(k, PhpKey::Str(s) if s == "aliases"))
    {
        *list = root_aliases
            .into_iter()
            .enumerate()
            .map(|(i, s)| (PhpKey::Int(i as i64), Php::Str(s)))
            .collect();
    }
    Php::Arr(vec![
        (PhpKey::Str("root".into()), root_entry),
        (
            PhpKey::Str("versions".into()),
            Php::Arr(
                versions
                    .into_iter()
                    .map(|(name, fields)| {
                        (
                            PhpKey::Str(name),
                            Php::Arr(
                                fields
                                    .into_iter()
                                    .map(|(k, v)| (PhpKey::Str(k), v))
                                    .collect(),
                            ),
                        )
                    })
                    .collect(),
            ),
        ),
    ])
}

/// `strnatcmp` (case-sensitive natural order)
fn natcmp(a: &str, b: &str) -> std::cmp::Ordering {
    let (ab, bb) = (a.as_bytes(), b.as_bytes());
    let (mut i, mut j) = (0, 0);
    while i < ab.len() && j < bb.len() {
        if ab[i].is_ascii_digit() && bb[j].is_ascii_digit() {
            let si = i;
            while i < ab.len() && ab[i].is_ascii_digit() {
                i += 1;
            }
            let sj = j;
            while j < bb.len() && bb[j].is_ascii_digit() {
                j += 1;
            }
            let na = a[si..i].trim_start_matches('0');
            let nb = b[sj..j].trim_start_matches('0');
            let ord = na.len().cmp(&nb.len()).then_with(|| na.cmp(nb));
            if ord != std::cmp::Ordering::Equal {
                return ord;
            }
        } else {
            if ab[i] != bb[j] {
                return ab[i].cmp(&bb[j]);
            }
            i += 1;
            j += 1;
        }
    }
    (ab.len() - i).cmp(&(bb.len() - j))
}

/// `FilesystemRepository::dumpToPhpCode`
fn dump_php(value: &Php, level: usize) -> String {
    let Php::Arr(items) = value else {
        unreachable!("installed.php root is an array")
    };
    let level = level + 1;
    let mut lines = String::from("array(\n");
    for (key, v) in items {
        lines.push_str(&"    ".repeat(level));
        match key {
            PhpKey::Int(i) => lines.push_str(&format!("{i} => ")),
            PhpKey::Str(s) => lines.push_str(&format!("{} => ", var_export_str(s))),
        }
        match v {
            Php::Arr(inner) => {
                if inner.is_empty() {
                    lines.push_str("array(),\n");
                } else {
                    lines.push_str(&dump_php(v, level));
                }
            }
            Php::Str(s) => {
                if matches!(key, PhpKey::Str(k) if k == "install_path") && !is_absolute_path(s) {
                    lines.push_str(&format!(
                        "__DIR__ . {},\n",
                        var_export_str(&format!("/{s}"))
                    ));
                } else {
                    lines.push_str(&format!("{},\n", var_export_str(s)));
                }
            }
            Php::Bool(b) => lines.push_str(if *b { "true,\n" } else { "false,\n" }),
            Php::Null => lines.push_str("null,\n"),
            Php::Int(i) => lines.push_str(&format!("{i},\n")),
        }
    }
    lines.push_str(&"    ".repeat(level - 1));
    lines.push(')');
    if level - 1 != 0 {
        lines.push_str(",\n");
    }
    lines
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn var_export_matches_php_layout() {
        let v = Php::Arr(vec![
            (
                PhpKey::Str("Psr\\Log\\".into()),
                Php::Arr(vec![(PhpKey::Int(0), Php::Str("/x".into()))]),
            ),
            (PhpKey::Str("n".into()), Php::Int(8)),
        ]);
        assert_eq!(
            var_export(&v, 0),
            "array (\n  'Psr\\\\Log\\\\' => \n  array (\n    0 => '/x',\n  ),\n  'n' => 8,\n)"
        );
    }

    #[test]
    fn natural_order() {
        assert_eq!(natcasecmp("a10", "a9"), std::cmp::Ordering::Greater);
        assert_eq!(natcasecmp("Abc", "abd"), std::cmp::Ordering::Less);
        assert_eq!(natcmp("1.10", "1.9"), std::cmp::Ordering::Greater);
    }
}
