#[allow(clippy::too_many_arguments)]
fn autoload_real_file(
    use_include_path: bool,
    target_dir_loader: Option<&str>,
    use_include_files: bool,
    suffix: &str,
    use_global_include_path: bool,
    prepend_autoloader: &str,
    check_platform: bool,
    options: &DumpOptions,
) -> String {
    let mut file = format!(
        "<?php\n\n// autoload_real.php @generated by Composer\n\nclass ComposerAutoloaderInit{suffix}\n{{\n    private static $loader;\n\n    public static function loadClassLoader($class)\n    {{\n        if ('Composer\\Autoload\\ClassLoader' === $class) {{\n            require __DIR__ . '/ClassLoader.php';\n        }}\n    }}\n\n    /**\n     * @return \\Composer\\Autoload\\ClassLoader\n     */\n    public static function getLoader()\n    {{\n        if (null !== self::$loader) {{\n            return self::$loader;\n        }}\n\n"
    );
    if check_platform {
        file.push_str("        require __DIR__ . '/platform_check.php';\n\n");
    }
    file.push_str(&format!(
        "        spl_autoload_register(array('ComposerAutoloaderInit{suffix}', 'loadClassLoader'), true, {prepend_autoloader});\n        self::$loader = $loader = new \\Composer\\Autoload\\ClassLoader(\\dirname(__DIR__));\n        spl_autoload_unregister(array('ComposerAutoloaderInit{suffix}', 'loadClassLoader'));\n\n"
    ));
    if use_include_path {
        file.push_str("        $includePaths = require __DIR__ . '/include_paths.php';\n        $includePaths[] = get_include_path();\n        set_include_path(implode(PATH_SEPARATOR, $includePaths));\n\n");
    }
    file.push_str(&format!(
        "        require __DIR__ . '/autoload_static.php';\n        call_user_func(\\Composer\\Autoload\\ComposerStaticInit{suffix}::getInitializer($loader));\n\n"
    ));
    if options.authoritative {
        file.push_str("        $loader->setClassMapAuthoritative(true);\n");
    }
    if options.apcu {
        let prefix = options
            .apcu_prefix
            .clone()
            .unwrap_or_else(|| crate::fs::random_hex(10));
        file.push_str(&format!(
            "        $loader->setApcuPrefix({});\n",
            var_export_str(&prefix)
        ));
    }
    if use_global_include_path {
        file.push_str("        $loader->setUseIncludePath(true);\n");
    }
    if target_dir_loader.is_some() {
        file.push_str(&format!("        spl_autoload_register(array('ComposerAutoloaderInit{suffix}', 'autoload'), true, true);\n\n"));
    }
    file.push_str(&format!(
        "        $loader->register({prepend_autoloader});\n\n"
    ));
    if use_include_files {
        file.push_str(&format!(
            "        $filesToLoad = \\Composer\\Autoload\\ComposerStaticInit{suffix}::$files;\n        $requireFile = \\Closure::bind(static function ($fileIdentifier, $file) {{\n            if (empty($GLOBALS['__composer_autoload_files'][$fileIdentifier])) {{\n                $GLOBALS['__composer_autoload_files'][$fileIdentifier] = true;\n\n                require $file;\n            }}\n        }}, null, null);\n        foreach ($filesToLoad as $fileIdentifier => $file) {{\n            $requireFile($fileIdentifier, $file);\n        }}\n\n"
        ));
    }
    file.push_str("        return $loader;\n    }\n");
    if let Some(loader) = target_dir_loader {
        file.push_str(loader);
    }
    file.push_str("}\n");
    file
}

/// PHP values as `var_export` prints them.
#[derive(Clone, Debug)]
pub enum Php {
    Str(String),
    Int(i64),
    Bool(bool),
    Null,
    Arr(Vec<(PhpKey, Php)>),
}

#[derive(Clone, Debug)]
pub enum PhpKey {
    Int(i64),
    Str(String),
}

fn var_export(value: &Php, level: usize) -> String {
    match value {
        Php::Str(s) => var_export_str(s),
        Php::Int(i) => i.to_string(),
        Php::Bool(b) => {
            if *b {
                "true".into()
            } else {
                "false".into()
            }
        }
        Php::Null => "NULL".into(),
        Php::Arr(items) => {
            let indent = "  ".repeat(level);
            let mut out = String::from("array (\n");
            for (k, v) in items {
                let key = match k {
                    PhpKey::Int(i) => i.to_string(),
                    PhpKey::Str(s) => var_export_str(s),
                };
                match v {
                    Php::Arr(_) => out.push_str(&format!(
                        "{indent}  {key} => \n{indent}  {},\n",
                        var_export(v, level + 1)
                    )),
                    _ => out.push_str(&format!(
                        "{indent}  {key} => {},\n",
                        var_export(v, level + 1)
                    )),
                }
            }
            out.push_str(&format!("{indent})"));
            out
        }
    }
}

fn static_file(
    suffix: &str,
    target_real: &str,
    vendor_path: &str,
    base_path: &str,
    autoloads: &Autoloads,
    class_map: &ClassMap,
) -> String {
    let mut file = format!(
        "<?php\n\n// autoload_static.php @generated by Composer\n\nnamespace Composer\\Autoload;\n\nclass ComposerStaticInit{suffix}\n{{\n"
    );

    let resolve = |p: &str| -> String {
        // what `require autoload_*.php` evaluates `$vendorDir . '/x'` / `$baseDir . '/x'` to
        let p = if is_absolute_path(p) {
            p.to_string()
        } else {
            format!("{base_path}/{p}")
        };
        let normalized = normalize_path(&p);
        if format!("{normalized}/").starts_with(&format!("{vendor_path}/")) {
            format!("{vendor_path}{}", &normalized[vendor_path.len()..])
        } else {
            let rel = normalize_path(&find_shortest_path(base_path, &normalized, true, false));
            if is_absolute_path(&rel) {
                rel
            } else {
                format!("{base_path}/{rel}")
            }
        }
    };
    let resolve_phar = |p: &str| -> String {
        let r = resolve(p);
        if Regex::new(r"\.phar([\\/]|$)").unwrap().is_match(&r) {
            format!("phar://{r}")
        } else {
            r
        }
    };

    let mut maps: Vec<(&str, Php)> = Vec::new();
    if !autoloads.files.is_empty() {
        maps.push((
            "files",
            Php::Arr(
                autoloads
                    .files
                    .iter()
                    .map(|(id, f)| (PhpKey::Str(id.clone()), Php::Str(resolve_phar(f))))
                    .collect(),
            ),
        ));
    }
    // ClassLoader::setPsr4 / set
    let mut prefix_lengths: Vec<(PhpKey, Php)> = Vec::new();
    let mut prefix_dirs: Vec<(PhpKey, Php)> = Vec::new();
    let mut fallback_psr4: Vec<(PhpKey, Php)> = Vec::new();
    for (ns, paths) in &autoloads.psr4 {
        let dirs = Php::Arr(
            paths
                .iter()
                .enumerate()
                .map(|(i, p)| (PhpKey::Int(i as i64), Php::Str(resolve_phar(p))))
                .collect(),
        );
        if ns.is_empty() {
            fallback_psr4 = match dirs {
                Php::Arr(d) => d,
                _ => vec![],
            };
        } else {
            let first = ns.chars().next().unwrap().to_string();
            let entry = (PhpKey::Str(ns.clone()), Php::Int(ns.len() as i64));
            match prefix_lengths
                .iter_mut()
                .find(|(k, _)| matches!(k, PhpKey::Str(s) if *s == first))
            {
                Some((_, Php::Arr(list))) => list.push(entry),
                _ => prefix_lengths.push((PhpKey::Str(first), Php::Arr(vec![entry]))),
            }
            prefix_dirs.push((PhpKey::Str(ns.clone()), dirs));
        }
    }
    if !prefix_lengths.is_empty() {
        maps.push(("prefixLengthsPsr4", Php::Arr(prefix_lengths)));
        maps.push(("prefixDirsPsr4", Php::Arr(prefix_dirs)));
    }
    if !fallback_psr4.is_empty() {
        maps.push(("fallbackDirsPsr4", Php::Arr(fallback_psr4)));
    }
    let mut prefixes_psr0: Vec<(PhpKey, Php)> = Vec::new();
    let mut fallback_psr0: Vec<(PhpKey, Php)> = Vec::new();
    for (ns, paths) in &autoloads.psr0 {
        let dirs = Php::Arr(
            paths
                .iter()
                .enumerate()
                .map(|(i, p)| (PhpKey::Int(i as i64), Php::Str(resolve_phar(p))))
                .collect(),
        );
        if ns.is_empty() {
            fallback_psr0 = match dirs {
                Php::Arr(d) => d,
                _ => vec![],
            };
        } else {
            let first = ns.chars().next().unwrap().to_string();
            let entry = (PhpKey::Str(ns.clone()), dirs);
            match prefixes_psr0
                .iter_mut()
                .find(|(k, _)| matches!(k, PhpKey::Str(s) if *s == first))
            {
                Some((_, Php::Arr(list))) => list.push(entry),
                _ => prefixes_psr0.push((PhpKey::Str(first), Php::Arr(vec![entry]))),
            }
        }
    }
    if !prefixes_psr0.is_empty() {
        maps.push(("prefixesPsr0", Php::Arr(prefixes_psr0)));
    }
    if !fallback_psr0.is_empty() {
        maps.push(("fallbackDirsPsr0", Php::Arr(fallback_psr0)));
    }
    if !class_map.is_empty() {
        maps.push((
            "classMap",
            Php::Arr(
                class_map
                    .map
                    .iter()
                    .map(|(c, p)| (PhpKey::Str(c.clone()), Php::Str(resolve_phar(p))))
                    .collect(),
            ),
        ));
    }

    let vendor_code = find_shortest_path_code(target_real, vendor_path, true, true, false);
    let base_code = find_shortest_path_code(target_real, base_path, true, true, false);
    let vendor_abs = var_export_str(&format!("{}/", vendor_path.trim_end_matches(['/', '\\'])));
    let base_abs = var_export_str(&format!("{}/", base_path.trim_end_matches(['/', '\\'])));
    let strip_quote = |s: &str| s[..s.len() - 1].to_string();
    let mut replacements: Vec<(String, String)> = vec![
        (
            format!(" => {}", strip_quote(&vendor_abs)),
            format!(" => {vendor_code} . '/"),
        ),
        (
            format!(
                " => {}",
                strip_quote(&var_export_str(&format!(
                    "phar://{}/",
                    vendor_path.trim_end_matches(['/', '\\'])
                )))
            ),
            format!(" => 'phar://' . {vendor_code} . '/"),
        ),
        (
            format!(" => {}", strip_quote(&base_abs)),
            format!(" => {base_code} . '/"),
        ),
        (
            format!(
                " => {}",
                strip_quote(&var_export_str(&format!(
                    "phar://{}/",
                    base_path.trim_end_matches(['/', '\\'])
                )))
            ),
            format!(" => 'phar://' . {base_code} . '/"),
        ),
    ];
    // strtr: longest keys first
    replacements.sort_by_key(|r| std::cmp::Reverse(r.0.len()));

    let mut initializer = String::new();
    for (prop, value) in &maps {
        let exported = var_export(value, 0);
        let replaced = strtr(&exported, &replacements);
        let re_indented: String = replaced
            .lines()
            .map(|line| {
                let spaces = line.len() - line.trim_start_matches(' ').len();
                format!("    {}{}", " ".repeat(spaces), line)
                    .trim_end()
                    .to_string()
            })
            .collect::<Vec<_>>()
            .join("\n");
        let value = re_indented.trim_start().to_string();
        file.push_str(&format!("    public static ${prop} = {value};\n\n"));
        if *prop != "files" {
            initializer.push_str(&format!(
                "            $loader->{prop} = ComposerStaticInit{suffix}::${prop};\n"
            ));
        }
    }
    file.push_str(&format!(
        "    public static function getInitializer(ClassLoader $loader)\n    {{\n        return \\Closure::bind(function () use ($loader) {{\n{initializer}\n        }}, null, ClassLoader::class);\n    }}\n}}\n"
    ));
    file
}

/// PHP `strtr` with an array: leftmost-longest, single pass.
fn strtr(input: &str, replacements: &[(String, String)]) -> String {
    let mut out = String::with_capacity(input.len());
    let mut i = 0;
    'outer: while i < input.len() {
        for (from, to) in replacements {
            if !from.is_empty() && input[i..].starts_with(from.as_str()) {
                out.push_str(to);
                i += from.len();
                continue 'outer;
            }
        }
        let c = input[i..].chars().next().unwrap();
        out.push(c);
        i += c.len_utf8();
    }
    out
}

fn platform_check(
    map: &PackageMap<'_>,
    check_extensions: bool,
    dev_package_names: &[String],
    ignored: &[String],
) -> Option<String> {
    let mut lowest_php = Bound::zero();
    let mut required_64bit = false;
    let mut required_extensions: BTreeMap<String, String> = BTreeMap::new();
    let mut extension_providers: HashMap<String, Vec<Constraint>> = HashMap::new();
    let ext_re = Regex::new(r"(?i)^ext-(.+)$").unwrap();
    for (package, _) in map {
        for link in package.replaces.iter().chain(package.provides.iter()) {
            if let Some(m) = ext_re.captures(&link.target) {
                extension_providers
                    .entry(m[1].to_string())
                    .or_default()
                    .push(link.constraint.clone());
            }
        }
    }
    let is_ignored = |name: &str| {
        ignored.iter().any(|pattern| {
            if let Some(prefix) = pattern.strip_suffix('*') {
                name.starts_with(prefix)
            } else {
                pattern == name
            }
        })
    };
    for (package, _) in map {
        if dev_package_names.contains(&package.name) {
            continue;
        }
        'links: for link in &package.requires {
            if is_ignored(&link.target) {
                continue;
            }
            if link.target == "php" || link.target == "php-64bit" {
                let lower = link.constraint.lower_bound();
                if lower.compare_to(&lowest_php, true) {
                    lowest_php = lower;
                }
            }
            if link.target == "php-64bit" {
                required_64bit = true;
            }
            if check_extensions && let Some(m) = ext_re.captures(&link.target) {
                let mut ext = m[1].to_string();
                if let Some(provided) = extension_providers.get(&ext) {
                    for p in provided {
                        if p.matches(&link.constraint) {
                            continue 'links;
                        }
                    }
                }
                if ext == "zend-opcache" {
                    ext = "zend opcache".into();
                }
                let exported = var_export_str(&ext);
                let line = if ext == "pcntl" || ext == "readline" {
                    format!(
                        "PHP_SAPI !== 'cli' || extension_loaded({exported}) || $missingExtensions[] = {exported};\n"
                    )
                } else {
                    format!("extension_loaded({exported}) || $missingExtensions[] = {exported};\n")
                };
                required_extensions.insert(exported, line);
            }
        }
    }

    let version_id = |b: &Bound| -> i64 {
        if b.is_zero() {
            return 0;
        }
        if b.is_positive_infinity() {
            return 99999;
        }
        let chunks: Vec<i64> = b
            .version
            .replace('-', ".")
            .split('.')
            .map(|c| {
                c.chars()
                    .take_while(|ch| ch.is_ascii_digit())
                    .collect::<String>()
                    .parse()
                    .unwrap_or(0)
            })
            .collect();
        chunks.first().copied().unwrap_or(0) * 10000
            + chunks.get(1).copied().unwrap_or(0) * 100
            + chunks.get(2).copied().unwrap_or(0)
    };
    let human = |b: &Bound| -> String {
        if b.is_zero() {
            return "0".into();
        }
        if b.is_positive_infinity() {
            return "99999".into();
        }
        b.version
            .replace('-', ".")
            .split('.')
            .take(3)
            .collect::<Vec<_>>()
            .join(".")
    };

    let mut required_php = String::new();
    if !lowest_php.is_zero() {
        let op = if lowest_php.inclusive { ">=" } else { ">" };
        required_php = format!(
            "\nif (!(PHP_VERSION_ID {op} {})) {{\n    $issues[] = 'Your Composer dependencies require a PHP version \"{op} {}\". You are running ' . PHP_VERSION . '.';\n}}\n",
            version_id(&lowest_php),
            human(&lowest_php)
        );
    }
    if required_64bit {
        required_php.push_str("\nif (PHP_INT_SIZE !== 8) {\n    $issues[] = 'Your Composer dependencies require a 64-bit build of PHP.';\n}\n");
    }
    let mut required_ext = String::new();
    if !required_extensions.is_empty() {
        let lines: String = required_extensions.values().cloned().collect();
        required_ext = format!(
            "\n$missingExtensions = array();\n{lines}\nif ($missingExtensions) {{\n    $issues[] = 'Your Composer dependencies require the following PHP extensions to be installed: ' . implode(', ', $missingExtensions) . '.';\n}}\n"
        );
    }
    if required_php.is_empty() && required_ext.is_empty() {
        return None;
    }
    Some(format!(
        "<?php\n\n// platform_check.php @generated by Composer\n\n$issues = array();\n{required_php}{required_ext}\nif ($issues) {{\n    if (!headers_sent()) {{\n        header('HTTP/1.1 500 Internal Server Error');\n    }}\n    if (!ini_get('display_errors')) {{\n        if (PHP_SAPI === 'cli' || PHP_SAPI === 'phpdbg') {{\n            fwrite(STDERR, 'Composer detected issues in your platform:' . PHP_EOL.PHP_EOL . implode(PHP_EOL, $issues) . PHP_EOL.PHP_EOL);\n        }} elseif (!headers_sent()) {{\n            echo 'Composer detected issues in your platform:' . PHP_EOL.PHP_EOL . str_replace('You are running '.PHP_VERSION.'.', '', implode(PHP_EOL, $issues)) . PHP_EOL.PHP_EOL;\n        }}\n    }}\n    throw new \\RuntimeException(\n        'Composer detected issues in your platform: ' . implode(' ', $issues)\n    );\n}}\n"
    ))
}

